/**
 * give-way-levels.mjs — choose the layout of every Give Way level.
 *
 *   node tools/give-way-levels.mjs
 *
 * Each level can be generated from many seed variants. For every level this
 * searches the variants (searchVariant in games/give-way/generator.js) for one
 * that covers at least minFill of the board and whose difficulty lands inside
 * its band's targets, as close to the middle of the ranges as it can find, and
 * writes the chosen variant numbers to games/give-way/levels.js. The game then
 * builds exactly that layout.
 *
 * Run it after any change to generator.js that alters layouts (and bump
 * GENERATOR_VERSION), or after changing a band's targets. It fails, and
 * writes nothing, if any level cannot be brought inside its targets.
 *
 * This is an authoring tool. It is not published and nothing here runs in
 * the browser.
 */

import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { MAX_LEVEL, GENERATOR_VERSION, searchVariant, difficulty } from '../games/give-way/generator.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = path.join(ROOT, 'games', 'give-way', 'levels.js');

const pct = (x) => `${Math.round(100 * x)}%`.padStart(4);
const variants = [];
const failures = [];
const t0 = performance.now();

console.log('\n  level  size   variant  tried  fill  open0 open20 open50');
for (let level = 1; level <= MAX_LEVEL; level++) {
  const { W, H } = difficulty(level);
  const found = searchVariant(level);
  variants.push(found.variant);
  const s = found.stats;
  const cols = s
    ? `${pct(found.fill)}  ${pct(s.open0)}  ${pct(s.open20)}  ${pct(s.open50)}`
    : `${pct(found.fill)}  (no variant met the fill and opening targets)`;
  console.log(
    `  ${String(level).padStart(5)}  ${`${W}x${H}`.padEnd(6)} ${String(found.variant).padStart(7)} ${String(found.tried).padStart(6)}  ${cols}${found.miss ? '  MISS' : ''}`
  );
  if (found.miss) failures.push(level);
}
console.log(`\n  searched in ${((performance.now() - t0) / 1000).toFixed(1)} s`);

if (failures.length) {
  console.error(`\n  ✗ No layout met the targets for level ${failures.join(', ')}. levels.js was not written.\n`);
  process.exit(1);
}

const rows = [];
for (let i = 0; i < variants.length; i += 10) {
  rows.push(`  ${variants.slice(i, i + 10).join(', ')}, // ${i + 1}-${Math.min(i + 10, variants.length)}`);
}
await writeFile(
  OUTPUT,
  `/* GENERATED by tools/give-way-levels.mjs — do not edit by hand.
 *
 * Seed variant used for each level, index 0 = level 1. Chosen so every level's
 * difficultyStats land inside its band's targets (see LEVEL_BANDS in
 * generator.js). Valid for GENERATOR_VERSION ${GENERATOR_VERSION}.
 */
export const LEVEL_VARIANTS = Object.freeze([
${rows.join('\n')}
]);
`
);
console.log(`  wrote games/give-way/levels.js\n`);
