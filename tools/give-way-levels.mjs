/**
 * give-way-levels.mjs — generate and store the 100 Give Way levels.
 *
 *   node tools/give-way-levels.mjs
 *
 * For each level this searches seeds (searchBoard in
 * games/give-way/generator.js) for a board that covers at least minFill of the
 * board and whose difficulty lands inside its band's targets, as close to the
 * middle of the ranges as it can find. The boards themselves are written to
 * games/give-way/levels.js in the compact text format (encodeBoard), so the
 * game never generates a level — it only decodes one. Searching may take
 * several minutes; that is fine, it only runs here.
 *
 * Run it after changing the generator or a band, then bump LEVELS_VERSION
 * below if any stored level changed (players are told their levels changed),
 * run the tests, and commit levels.js. It fails, and writes nothing, if any
 * level cannot be brought inside its targets.
 *
 * This is an authoring tool. It is not published and nothing here runs in
 * the browser.
 */

import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { MAX_LEVEL, difficulty, levelSeed, searchBoard, encodeBoard } from '../games/give-way/generator.js';

/* Bump whenever the stored levels change. Saves record it, and the game tells
   players when it differs from theirs. */
const LEVELS_VERSION = 1;

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = path.join(ROOT, 'games', 'give-way', 'levels.js');

const pct = (x) => `${Math.round(100 * x)}%`.padStart(4);
const lines = [];
const failures = [];
const t0 = performance.now();

console.log('\n  level  band    size    tried  arrows  len  fill  open0 open20 open50');
for (let level = 1; level <= MAX_LEVEL; level++) {
  const params = difficulty(level);
  const found = searchBoard(params, (v) => levelSeed(level, v), { level, maxVariants: 20000 });
  const s = found.stats;
  const cols = s
    ? `${pct(found.fill)}  ${pct(s.open0)}  ${pct(s.open20)}  ${pct(s.open50)}`
    : `${pct(found.fill)}  (no board met the fill and opening targets)`;
  console.log(
    `  ${String(level).padStart(5)}  ${params.band.padEnd(6)}  ${`${params.W}x${params.H}`.padEnd(6)} ${String(found.tried).padStart(6)}  ${String(found.board.arrows.length).padStart(6)}  ${found.shape.avgLen.toFixed(1).padStart(4)}  ${cols}${found.miss ? '  MISS' : ''}`
  );
  if (found.miss) failures.push(level);
  lines.push(encodeBoard(found.board));
}
console.log(`\n  searched in ${((performance.now() - t0) / 1000).toFixed(1)} s`);

if (failures.length) {
  console.error(`\n  ✗ No board met the targets for level ${failures.join(', ')}. levels.js was not written.\n`);
  process.exit(1);
}

const source = `/* GENERATED by tools/give-way-levels.mjs — do not edit by hand.
 *
 * The ${MAX_LEVEL} levels, one board per line in the text format described at
 * encodeBoard in generator.js. Each was chosen to cover at least 90% of the
 * board, keep arrows long and almost never head to tail, and land inside its band's
 * difficulty targets (see BANDS).
 */

import { decodeBoard } from './generator.js';

/* Bumped whenever the stored levels change. */
export const LEVELS_VERSION = ${LEVELS_VERSION};

const LEVELS = Object.freeze([
${lines.map((l) => `  '${l}',`).join('\n')}
]);

export const LEVEL_COUNT = LEVELS.length;

export function loadLevel(level) {
  return decodeBoard(LEVELS[level - 1], level);
}
`;
await writeFile(OUTPUT, source);
console.log(`  wrote games/give-way/levels.js (${(Buffer.byteLength(source) / 1024).toFixed(0)} KB)\n`);
